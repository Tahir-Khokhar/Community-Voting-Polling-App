"""
Template context processors for the polls app.

These expose a small set of global values to every template without each
view having to pass them explicitly.
"""

from django.conf import settings


def poll_settings(_request):
    """Expose the POLL_SETTINGS dict (HTMX interval etc.) to templates."""
    return {"POLL_SETTINGS": settings.POLL_SETTINGS}


def csp_nonce(request):
    """Expose the per-request CSP nonce so inline scripts can use it.

    The nonce is generated by ContentSecurityPolicyMiddleware and attached to
    the request; templates apply it as ``nonce="{{ csp_nonce }}"`` on inline
    ``<script>`` tags so they are allowed by the CSP without 'unsafe-inline'.
    """
    return {"csp_nonce": getattr(request, "csp_nonce", "")}
